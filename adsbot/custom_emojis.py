_SORTED_EMOJIS = sorted(MESSAGE_EMOJI_IDS.keys(), key=len, reverse=True)
_EMOJI_REGEX = re.compile('(' + '|'.join(re.escape(k) for k in _SORTED_EMOJIS) + ')')


def premiumize_text(text: str) -> str:
    """
    Transforms all standard emojis into Telegram animated custom emojis.
    Skips emojis that are already inside a <tg-emoji> tag.
    """
    if not text:
        return text

    segments = []
    last_idx = 0
    tg_tag_pattern = re.compile(r'<tg-emoji\s+emoji-id="[^"]+">.*?</tg-emoji>', re.DOTALL)

    for match in tg_tag_pattern.finditer(text):
        pre_text = text[last_idx:match.start()]
        if pre_text:
            def repl(m):
                ch = m.group(0)
                eid = MESSAGE_EMOJI_IDS.get(ch)
                if eid:
                    return f'<tg-emoji emoji-id="{eid}">{ch}</tg-emoji>'
                return ch
            segments.append(_EMOJI_REGEX.sub(repl, pre_text))
        
        segments.append(match.group(0))
        last_idx = match.end()

    tail = text[last_idx:]
    if tail:
        def repl(m):
            ch = m.group(0)
            eid = MESSAGE_EMOJI_IDS.get(ch)
            if eid:
                return f'<tg-emoji emoji-id="{eid}">{ch}</tg-emoji>'
            return ch
        segments.append(_EMOJI_REGEX.sub(repl, tail))

    return "".join(segments)
